//! Platform abstraction of Own Keyboard Switch.
//!
//! The engine talks to the operating system only through the traits defined
//! here. `okbs-platform-windows` and `okbs-platform-linux` implement them.
//! Everything is `Send`, so implementations can live on dedicated threads.

pub mod autoreplace_gate;
mod diagnostics;
mod error;
mod types;

