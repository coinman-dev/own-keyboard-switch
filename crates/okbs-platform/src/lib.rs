/// An explicit choice from the insertion list. Do not log its text payload.
#[derive(Clone)]
pub struct AutoreplaceInsertion {
    pub item: okbs_core::config::AutoReplaceItem,
    pub target: Option<InputTarget>,
}

impl std::fmt::Debug for AutoreplaceInsertion {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("AutoreplaceInsertion")
            .field("target", &self.target)
            .finish_non_exhaustive()
    }
}

